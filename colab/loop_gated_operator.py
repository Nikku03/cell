"""Loop 257. Context parameterises the operator -- on a substrate that is actually dense.

THE PROPOSAL THIS IMPLEMENTS, AND THE TWO THINGS CHANGED, EACH FOR A MEASURED REASON.

The structural idea is right and it is not mine: context should PARAMETERISE how a perturbation
propagates, rather than being concatenated beside it. Loop 255 is the evidence -- three agents
independently found that a feature constant across landmarks within a (gene, line) pair contributes
only an offset, and a within-profile correlation ignores offset and scale, so every hand-written
arm predicted ONE FIXED DIRECTION per held-out line, which is exactly what the residual subtracts.
Those arms could not express an interaction at all. Parameterising an operator is the fix.

Loop 256 then showed that CONCATENATION is not the fix: a gene tower and a line tower joined by an
MLP scored 0.3001 and 0.3017 against the additive baseline's 0.4518 -- 0.15 WORSE. Two changes
follow, and both come from measurement rather than taste.

  1. PREDICT A CORRECTION, NOT THE PROFILE. Loop 256's decoder had to rebuild all 978 landmarks
     through a 160-dimensional bottleneck, so it discarded what the gene mean already carried. Here
     the output is  additive_baseline + correction , with the correction initialised at zero. The
     model starts exactly at 0.4518 and can only add. This is the single largest change.

  2. GATE A DENSE SUBSTRATE, NOT OmniPath. The proposal gates the signed OmniPath adjacency. That
     graph cannot carry it, measured three ways:
         signed edges from a knocked-down gene to a landmark   9,087
         density over possible (gene x landmark) cells         0.21%
         signed landmark targets per gene                      median 0; 63% of genes have none
         loop 242: reversing EVERY arrow left 102% of the effect
         loop 253: signed edges x expressed-here = -0.0000 on the interaction
     A gate on a structure that is 99.8% empty and direction-blind has nothing to modulate. So the
     substrate is a LEARNED low-rank operator basis, which is dense by construction, and context
     mixes it:

         correction  =  sum_k  g_c[k] * ( M_k  e_p )        g_c = sigmoid( Hyper( z_c ) )

     This is the hyper-bilinear form -- the effective operator W(z_c) = sum_k g_c[k] M_k is
     generated by context, exactly as proposed -- with the empty substrate replaced by one that
     can hold signal.

WHAT ELSE FROM THE PROPOSAL IS AND IS NOT HERE, so the record is not inflated.
  Variance-weighted loss: NOT used. Its premise, that over 99% of genes do not move, is false on
  this data -- 24.6% of (signature, landmark) cells exceed |z|=1, 5.7% exceed |z|=2, and the median
  signature moves 41 of 978 landmarks. LINCS Level 5 is already differential and landmark-selected,
  so the sparsity the loss corrects for is not present.
  Two-stage pretraining on 1,076 DepMap lines: NOT used, and this is the one I most wanted to keep.
  Measured first: damaging mutations reconstruct held-out baseline expression at r = 0.6182 against
  0.5926 for simply predicting the training mean profile, so mutation adds +0.0256, and only 246 of
  19,097 genes are damaged in 20 or more lines. The pretraining stage would have almost nothing to
  learn.
  Sequence embeddings in z_c: NOT used, because they cannot vary with context. A gene's sequence is
  the same in all nine lines apart from sparse mutated positions, so a Borzoi or AlphaGenome
  embedding is a GENE property. Placed in the context tower it would be constant across lines and
  contribute precisely the degenerate offset this design exists to escape.
  A paralogue branch with gamma/(1+CNV): NOT used, because it hard-codes buffering and the measured
  sign disagrees -- loops 239-240 fitted the ANTI-buffering direction and loop 255's paralogue arm
  scored -0.0025 against baseline.

PREDECLARED, BEFORE ANY NUMBER.

  I1 DOES THE HARNESS REPRODUCE THE BASELINE?
     The additive model recomputed here. Gate: PASS iff within 0.02 of loop 252's 0.4477.
     Everything requires it.

  I2 DOES THE GATED OPERATOR BEAT THE ADDITIVE BASELINE?      -- requires I1
     Gate: PASS iff at least +0.02 paired over held-out (gene, line) pairs. Note the architecture
     starts AT the baseline by construction, so this gate asks whether the learned correction is
     positive out of sample, not whether the model can reach the baseline.

  I3 DOES CONTEXT-GATING MATTER, OR ONLY THE EXTRA CAPACITY?      -- requires I1. The load-bearing gate.
     The identical network with K=1, which removes the mixture and leaves a single context-blind
     operator of the same form.
     Gate: PASS iff the gated model exceeds the single-operator model by at least 0.01. A FAIL
     means the correction is a better gene model, not a context model, and the whole premise of
     context-parameterisation is unsupported here.

  I4 DID THE NETWORK HELP, OR THE FEATURES?      -- requires I1
     Ridge given the same gene embedding and context vector, predicting the same correction.
     Gate: PASS iff the network exceeds it by at least 0.01. Loop 241 lost this by -0.0155 and
     -0.0170, loop 251 by -0.0088, and loop 242's signed GCN is the only architecture in this
     project ever to win it.

  I5 IS THE ADVANTAGE LARGER THAN THE SEED NOISE?      -- requires I2, VOID if I2 found nothing
     Three seeds. Gate: PASS iff I2's margin exceeds twice the across-seed standard deviation.

  I6 CONTROL: THE WRONG CELL LINE.      -- requires I3, VOID if I3's margin is under 0.005
     The hypernetwork fed another line's measured properties, everything else identical.
     Gate: PASS iff I3's advantage collapses to under 25%.

  I7 WHAT THIS CANNOT SHOW -- written before the run.
     Nine cell lines is nine points for the hypernetwork to generalise over, and it must map
     measured properties to K gate values from eight training examples. Any positive should be
     suspected of memorising those eight, which is what I6 catches and why I5 uses three seeds.
     A learned operator basis is dense but it is not a physical network. Nothing here identifies
     WHICH interactions the gates correspond to, and a win would not recover the mechanism loops
     253 and 255 failed to find.
     The gene embedding is built from the gene's own response in other lines, so this generalises
     across CONTEXTS and not across genes; it cannot predict a gene never perturbed anywhere.
     978 landmarks and shRNA, not a transcriptome and not a clean knockout.
"""
