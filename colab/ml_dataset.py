"""THE DATA CONTRACT: what goes to a model, in what form, where it lives, and what may not be done to it.

WHY THIS IS A SEPARATE MODULE FROM THE EXPERIMENT. "Give the model all the data and see if it can
predict" is the request that produces the most confident wrong answers in applied ML, because the
failure is never in the architecture -- it is in the split. This module exists to make the split,
the units and the provenance an ARTEFACT on disk that any framework can consume and that anyone can
audit, rather than a few lines buried in a training script.

WHAT CANNOT BE LEARNED, AND WHY IT IS NOT HERE. This repository holds three kinds of thing and only
one of them is training data:

    per-gene scalars   abundance, half-life, kcat, K_M            -> targets and features
    graph structure    TF edges, PPI, reactions                   -> features, and degree-confounded
    physical law       dP/dt, tanh(b*T/4), Smoluchowski, budgets  -> NOT TRAINING DATA

The third kind is the one people try hardest to feed a network. It should not be. tanh(b*T/4) is
exact; a model that learns it approximately is strictly worse than the closed form, and a model
trained on trajectories generated BY those equations learns the integrator, not the cell. What the
laws are for here is the evaluation harness: they give free falsification tests that need no
held-out data at all. A predicted k_cat/K_M above the diffusion limit is wrong without anyone
having to measure anything.

THE TASK. Predict log10 k_cat from enzyme sequence and substrate structure. It is chosen over the
alternatives for reasons that are measured, not aesthetic:

    it is the parameter the model most lacks      loop 124: 72.6% of reaction kcats are predicted,
                                                  and they do not beat a constant 1.85/s
    the input cannot be an abundance proxy        sequence and SMILES carry no copy number
    there is a hard physical ceiling              loop 126's Smoluchowski bound, unfitted
    there is a measured noise floor               1.15x, the same protein and substrate measured
                                                  twice, so the irreducible RMSE is log10(1.15)
                                                  = 0.061 and nothing can beat it
    there is a published baseline                 DLKcat and TurNuP solve this exact problem

THE SPLIT IS THE EXPERIMENT. Homologous enzymes share turnover numbers, so a random split puts a
protein's close relatives in train and itself in test and reports memorisation as skill. Sequences
are therefore clustered by MinHash 5-mer similarity with union-find over LSH bands, and whole
clusters are assigned to folds. The clustering is APPROXIMATE, so the manifest also records a
direct leakage audit: the maximum k-mer Jaccard between any test sequence and its nearest training
sequence. An unaudited cluster split is just a random split with extra steps.

FIVE BASELINES SHIP WITH THE DATA, because a number without them is not a result:

    constant           the training median. Loop 124 showed it beating CatPred, so it is not a
                       formality
    nearest neighbour  by sequence identity. THE ONE THAT MATTERS -- if a homology lookup ties the
                       network, the network learned homology
    composition        amino acid frequencies and length only, no structure, no PLM
    EC median          where an EC number exists
    publication count  on the human subset, because fame has beaten the biology in six loops here

WHERE IT LIVES.  colab/data/ml/
    kcat_records.tsv      one row per measurement: seq_id, smiles_id, organism, ec, log10_kcat,
                          gene (human only), cluster_id, fold
    esm2_8M_mean.npy      float16 [n_seq, 320], mean-pooled ESM2-t6-8M, row order = esm_sequences
    esm_sequences.json    the sequence strings, index-aligned to the embedding matrix
    substrate_ecfp.npy    uint8 [n_smiles, 256], Morgan radius 2 folded to 2048 bits, packed
    substrate_smiles.json index-aligned SMILES
    seq_features.npy      float32 [n_seq, 25], length and amino acid composition
    MANIFEST.json         units, provenance hashes, split rule, leakage audit, baseline scores

UNITS, STATED ONCE.  k_cat is per second. The target is log10 of it. Fold-error and RMSE in log10
are the same statement: RMSE 1.0 means a typical prediction is 10x out.

-> colab/data/ml/
"""
import collections
import hashlib
import json
import os
import re
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import loop_replication as LR  # noqa: E402

ML = Path("colab/data/ml")
DLK = LR.SC / "dlkcat.json"
PROT = LR.SC / "human_proteome.fasta.gz"
SEED = 13100
KMER = 5
N_HASH = 128
N_BANDS = 32          # 32 bands x 4 rows; sequences sharing a band bucket become cluster candidates
N_FOLDS = 5
AA = "ACDEFGHIKLMNPQRSTVWY"


def log(s=""):
    print(s, flush=True)


def num(v):
    try:
        return float(v)
    except (TypeError, ValueError):
        return None


def kmers(s, k=KMER):
    return {s[i:i + k] for i in range(len(s) - k + 1)}


def minhash(sets, n_hash=N_HASH, seed=SEED):
    """MinHash signatures. Cheap, and the manifest audits how well it actually separated."""
    rng = np.random.default_rng(seed)
    a = rng.integers(1, 2 ** 61 - 1, n_hash, dtype=np.int64)
    b = rng.integers(0, 2 ** 61 - 1, n_hash, dtype=np.int64)
    P = (1 << 61) - 1
    sig = np.full((len(sets), n_hash), np.iinfo(np.int64).max, dtype=np.int64)
    for i, s in enumerate(sets):
        if not s:
            continue
        h = np.array([int.from_bytes(hashlib.blake2b(x.encode(), digest_size=8).digest(),
                                     "little") % P for x in s], dtype=np.int64)
        sig[i] = ((a[None, :] * h[:, None] + b[None, :]) % P).min(0)
    return sig


class UF:
    def __init__(self, n):
        self.p = list(range(n))

    def find(self, x):
        while self.p[x] != x:
            self.p[x] = self.p[self.p[x]]
            x = self.p[x]
        return x

    def union(self, x, y):
        rx, ry = self.find(x), self.find(y)
        if rx != ry:
            self.p[rx] = ry


def cluster(sig, n_bands=N_BANDS):
    rows = sig.shape[1] // n_bands
    uf = UF(len(sig))
    for b in range(n_bands):
        buckets = collections.defaultdict(list)
        for i in range(len(sig)):
            buckets[tuple(sig[i, b * rows:(b + 1) * rows].tolist())].append(i)
        for v in buckets.values():
            for j in v[1:]:
                uf.union(v[0], j)
    return np.array([uf.find(i) for i in range(len(sig))])


def main():
    t0 = time.time()
    ML.mkdir(parents=True, exist_ok=True)
    log("=" * 100)
    log("  THE DATA CONTRACT -- building colab/data/ml/")
    log("=" * 100)
    log()

    d = json.load(open(DLK))
    rec = [x for x in d if x.get("Sequence") and (num(x.get("Value")) or 0) > 0
           and x.get("Smiles")]
    log(f"  DLKcat: {len(d):,} records -> {len(rec):,} with a sequence, a SMILES and a "
        f"positive value")
    seqs = sorted({x["Sequence"] for x in rec})
    smis = sorted({x["Smiles"] for x in rec})
    si = {s: i for i, s in enumerate(seqs)}
    mi = {s: i for i, s in enumerate(smis)}
    log(f"  {len(seqs):,} unique sequences, {len(smis):,} unique substrates, "
        f"{len({x.get('Organism') for x in rec}):,} organisms")

    # ---------------------------------------------------------------- clustering + folds
    log("\n  clustering sequences by MinHash 5-mer similarity (LSH banding + union-find)")
    ksets = [kmers(s) for s in seqs]
    sig = minhash(ksets)
    cl = cluster(sig)
    ncl = len(set(cl.tolist()))
    sizes = collections.Counter(cl.tolist())
    log(f"    {ncl:,} clusters over {len(seqs):,} sequences; largest {max(sizes.values()):,}, "
        f"singletons {sum(1 for v in sizes.values() if v == 1):,}")
    rng = np.random.default_rng(SEED)
    cids = sorted(set(cl.tolist()))
    rng.shuffle(cids)
    fold_of_cluster = {c: i % N_FOLDS for i, c in enumerate(cids)}
    seq_fold = np.array([fold_of_cluster[c] for c in cl])
    log(f"    {N_FOLDS} folds assigned by CLUSTER, never by sequence")

    # ---------------------------------------------------------------- leakage audit
    log("\n  LEAKAGE AUDIT -- max k-mer Jaccard between a test sequence and its nearest train one")
    audit = {}
    for f in range(1):                      # fold 0 as the audited example; the rule is identical
        te = np.flatnonzero(seq_fold == f)
        tr = np.flatnonzero(seq_fold != f)
        sub = rng.choice(te, size=min(200, len(te)), replace=False)
        best = []
        trs = [ksets[j] for j in tr]
        for i in sub:
            ki = ksets[i]
            if not ki:
                continue
            m = 0.0
            for kj in trs:
                if not kj:
                    continue
                inter = len(ki & kj)
                if inter:
                    m = max(m, inter / len(ki | kj))
            best.append(m)
        best = np.array(best)
        audit[f"fold{f}"] = {"n_sampled": int(len(best)), "median": float(np.median(best)),
                             "p90": float(np.percentile(best, 90)), "max": float(best.max())}
        log(f"    fold {f}: median {np.median(best):.3f}, 90th {np.percentile(best, 90):.3f}, "
            f"max {best.max():.3f}  (1.0 would mean an identical sequence is in train)")

    # ---------------------------------------------------------------- substrate fingerprints
    log("\n  substrate fingerprints: Morgan radius 2, 2048 bits, packed to uint8")
    from rdkit import Chem, RDLogger
    from rdkit.Chem import rdFingerprintGenerator
    RDLogger.DisableLog("rdApp.*")
    gen = rdFingerprintGenerator.GetMorganGenerator(radius=2, fpSize=2048)
    FP = np.zeros((len(smis), 256), dtype=np.uint8)
    bad = 0
    for s, i in mi.items():
        m = Chem.MolFromSmiles(s)
        if m is None:
            bad += 1
            continue
        arr = np.frombuffer(gen.GetFingerprintAsNumPy(m).astype(np.uint8).tobytes(),
                            dtype=np.uint8)
        FP[i] = np.packbits(arr)
    log(f"    {len(smis) - bad:,} parsed, {bad} unparseable SMILES (left as all-zero and flagged)")

    # ---------------------------------------------------------------- sequence features
    log("\n  composition features: length + 20 amino acid frequencies + 4 physicochemical classes")
    SF = np.zeros((len(seqs), 25), dtype=np.float32)
    groups = {"hydrophobic": "AILMFVWY", "charged": "DEKR", "polar": "STNQCH", "special": "GP"}
    for s, i in si.items():
        n = max(len(s), 1)
        SF[i, 0] = np.log10(n)
        for j, a in enumerate(AA):
            SF[i, 1 + j] = s.count(a) / n
        for j, (_, gg) in enumerate(groups.items()):
            SF[i, 21 + j] = sum(s.count(c) for c in gg) / n

    # ---------------------------------------------------------------- human gene mapping
    import gzip
    s2g, nm, buf = {}, None, []
    with gzip.open(PROT, "rt") as f:
        for ln in f:
            if ln.startswith(">"):
                if nm and buf:
                    s2g["".join(buf)] = nm
                buf, nm = [], None
                for p in ln.split():
                    if p.startswith("GN="):
                        nm = p[3:]
                        break
            else:
                buf.append(ln.strip())
    if nm and buf:
        s2g["".join(buf)] = nm

    # ---------------------------------------------------------------- records
    rows = []
    for x in rec:
        i = si[x["Sequence"]]
        rows.append({"seq_id": i, "smiles_id": mi[x["Smiles"]],
                     "organism": x.get("Organism", ""), "ec": x.get("ECNumber", ""),
                     "substrate": x.get("Substrate", ""),
                     "log10_kcat": float(np.log10(num(x["Value"]))),
                     "gene": s2g.get(x["Sequence"], ""),
                     "cluster_id": int(cl[i]), "fold": int(seq_fold[i])})
    y = np.array([r["log10_kcat"] for r in rows])
    log(f"\n  {len(rows):,} records written; log10 kcat mean {y.mean():+.3f} sd {y.std():.3f}")
    log(f"    a CONSTANT predictor therefore scores RMSE {y.std():.3f} log10 "
        f"= {10 ** y.std():.1f}x typical fold error")
    log(f"    the experimental floor is log10(1.15) = {np.log10(1.15):.3f}, which nothing can beat")
    log(f"    human records: {sum(1 for r in rows if r['organism'] == 'Homo sapiens'):,}, "
        f"of which {sum(1 for r in rows if r['gene']):,} map to a gene symbol")

    with open(ML / "kcat_records.tsv", "w") as f:
        cols = ["seq_id", "smiles_id", "organism", "ec", "substrate", "log10_kcat", "gene",
                "cluster_id", "fold"]
        f.write("\t".join(cols) + "\n")
        for r in rows:
            f.write("\t".join(str(r[c]).replace("\t", " ") for c in cols) + "\n")
    np.save(ML / "substrate_ecfp.npy", FP)
    json.dump(smis, open(ML / "substrate_smiles.json", "w"))
    np.save(ML / "seq_features.npy", SF)
    json.dump(seqs, open(ML / "sequences.json", "w"))

    man = {
        "dataset": "kcat from enzyme sequence and substrate",
        "built_by": "colab/ml_dataset.py",
        "source": {"file": str(DLK), "sha256_16": RM_digest(DLK),
                   "citation": "DLKcat Kcat_combination_0918 (BRENDA + SABIO-RK compilation)"},
        "units": {"kcat": "per second", "target": "log10(kcat / s^-1)"},
        "n_records": len(rows), "n_sequences": len(seqs), "n_substrates": len(smis),
        "target_mean": float(y.mean()), "target_sd": float(y.std()),
        "constant_baseline_rmse_log10": float(y.std()),
        "experimental_floor_rmse_log10": float(np.log10(1.15)),
        "split": {"rule": "MinHash 5-mer LSH clusters, whole clusters assigned to folds",
                  "n_clusters": ncl, "n_folds": N_FOLDS, "seed": SEED,
                  "leakage_audit": audit,
                  "WARNING": "a random split leaks badly here; homologous enzymes share kcat"},
        "files": {
            "kcat_records.tsv": "one row per measurement; fold is the ONLY split to use",
            "esm2_8M_mean.npy": "float16 [n_seq, 320] mean-pooled ESM2-t6-8M, "
                                "row order = sequences.json",
            "sequences.json": "sequence strings, index-aligned to seq_id and the embedding",
            "substrate_ecfp.npy": "uint8 [n_smiles, 256], Morgan r=2 2048-bit packed; "
                                  "np.unpackbits to use",
            "substrate_smiles.json": "SMILES, index-aligned to smiles_id",
            "seq_features.npy": "float32 [n_seq, 25]: log10 length, 20 aa frequencies, "
                                "4 class fractions"},
        "forbidden": [
            "random splits -- use the fold column",
            "training on physical law; tanh(b*T/4) and Smoluchowski are exact and belong in "
            "evaluation, not in the loss",
            "scoring against DLKcat any model whose features were derived from DLKcat "
            "(loop 129 lost 160 of 169 validation genes to exactly this)",
            "reporting a score without the constant, nearest-neighbour and composition baselines"],
        "seconds": time.time() - t0,
    }
    json.dump(man, open(ML / "MANIFEST.json", "w"), indent=1)
    log(f"\n  -> {ML}/  ({len(list(ML.iterdir()))} files)")
    for p in sorted(ML.iterdir()):
        log(f"     {p.name:<24} {p.stat().st_size / 1e6:>8.2f} MB")
    log(f"\n  [{time.time() - t0:.1f}s]")


def RM_digest(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for chunk in iter(lambda: f.read(1 << 20), b""):
            h.update(chunk)
    return h.hexdigest()[:16]


if __name__ == "__main__":
    main()
